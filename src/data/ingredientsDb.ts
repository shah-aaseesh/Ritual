export function findIngredientMatch(text: string): IngredientInfo | undefined {
  const normalized = text.toLowerCase().trim();
  return INGREDIENTS_DATABASE.find(item => {
    if (normalized.includes(item.name.toLowerCase()) || item.name.toLowerCase().includes(normalized)) {
      return true;
    }
    return item.aliases.some(alias => normalized.includes(alias.toLowerCase()) || alias.toLowerCase().includes(normalized));
  });
}
